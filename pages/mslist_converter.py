@callback(
    Output("mslist-converter-command-container", "children"), 
    Input("mslist-converter-command-select", "value"),
)
def mslist_converter_select_command(value):
    if value == "msisensor-pro":
        return make_pro()
    elif value == "mantis":
        return make_mantis()
    else:
        return None

@callback(
    Output("mslist-converter-pro-start-button", "disabled"),
    Input("mslist-converter-pro-microsat-list-file-select", "value"),
)
def mslist_converter_pro_start_button(microsatellite_list):
    return not bool(microsatellite_list)

@callback(
    Output("notification-container", "sendNotifications", allow_duplicate=True),
    Input("mslist-converter-pro-start-button", "n_clicks"),
    State("mslist-converter-command-select", "value"),
    State("mslist-converter-pro-microsat-list-file-select", "value"),
    State("mslist-converter-pro-output-name-input", "value"),
    prevent_initial_call=True,
)
def mslist_converter_pro_start_job(
    n_clicks,
    command_key,
    microsatellite_list,
    output_name,
):
    if not n_clicks:
        return no_update

    try:
        create_job(
            tool=tool,
            command=tool.commands.get(command_key),
            microsatellite_list=microsatellite_list,
            output=build_output_name(microsatellite_list, output_name, MICROSAT_LIST_PRO_EXT[0]),
        )

        return job_started_notification(f"{tool.name} pro started")

    except Exception as e:
        return job_started_failed_notification(e)

    
